import {
  CUSTOMER_ROLE_DEFAULT_NAME,
  CUSTOMER_ROLE_PERMISSION_STATEMENTS,
  CUSTOMER_ROLE_SESSION_SECONDS,
} from '@cloudsentry/shared-types';

export interface CustomerRoleTemplateOptions {
  /** CloudSentry platform account ID. When omitted the template asks for it as a parameter. */
  trustedAccountId?: string;
  /** External ID for this customer. When omitted the template asks for it as a parameter. */
  externalId?: string;
  roleName?: string;
}

/**
 * CloudFormation template (JSON) for the read-only role customers deploy in their account.
 * The trust policy allows only the CloudSentry account, and only with the customer's external ID
 * (confused-deputy protection). The permissions come verbatim from CUSTOMER_ROLE_PERMISSION_STATEMENTS.
 */
export function customerRoleTemplate(options: CustomerRoleTemplateOptions = {}): Record<string, unknown> {
  return {
    AWSTemplateFormatVersion: '2010-09-09',
    Description: 'CloudSentry read-only cross-account access role (no write permissions).',
    Parameters: {
      TrustedAccountId: {
        Type: 'String',
        AllowedPattern: '^\\d{12}$',
        Description: 'AWS account ID of the CloudSentry platform.',
        ...(options.trustedAccountId ? { Default: options.trustedAccountId } : {}),
      },
      ExternalId: {
        Type: 'String',
        MinLength: 2,
        MaxLength: 1224,
        AllowedPattern: '^[\\w+=,.@:\\/-]+$',
        Description: 'External ID generated by CloudSentry for this account.',
        ...(options.externalId ? { Default: options.externalId } : {}),
      },
      RoleName: {
        Type: 'String',
        Default: options.roleName ?? CUSTOMER_ROLE_DEFAULT_NAME,
        AllowedPattern: '^CloudSentry[\\w+=,.@-]{0,52}$',
        Description: 'Role name. Must start with CloudSentry.',
      },
    },
    Resources: {
      CloudSentryReadOnlyRole: {
        Type: 'AWS::IAM::Role',
        Properties: {
          RoleName: { Ref: 'RoleName' },
          Description: 'Read-only access for CloudSentry cost optimization scans',
          MaxSessionDuration: Math.max(CUSTOMER_ROLE_SESSION_SECONDS, 3600),
          AssumeRolePolicyDocument: {
            Version: '2012-10-17',
            Statement: [
              {
                Effect: 'Allow',
                Principal: { AWS: { 'Fn::Sub': 'arn:${AWS::Partition}:iam::${TrustedAccountId}:root' } },
                Action: 'sts:AssumeRole',
                Condition: { StringEquals: { 'sts:ExternalId': { Ref: 'ExternalId' } } },
              },
            ],
          },
          Policies: [
            {
              PolicyName: 'CloudSentryReadOnly',
              PolicyDocument: {
                Version: '2012-10-17',
                Statement: CUSTOMER_ROLE_PERMISSION_STATEMENTS.map((s) => ({
                  Sid: s.Sid,
                  Effect: s.Effect,
                  Action: [...s.Action],
                  Resource: s.Resource,
                })),
              },
            },
          ],
          Tags: [{ Key: 'ManagedBy', Value: 'CloudSentry' }],
        },
      },
    },
    Outputs: {
      RoleArn: {
        Description: 'Paste this ARN into CloudSentry',
        Value: { 'Fn::GetAtt': ['CloudSentryReadOnlyRole', 'Arn'] },
      },
    },
  };
}

/** Every IAM action the customer role grants (for documentation and tests). */
export function customerRoleActions(): string[] {
  return CUSTOMER_ROLE_PERMISSION_STATEMENTS.flatMap((s) => [...s.Action]);
}
