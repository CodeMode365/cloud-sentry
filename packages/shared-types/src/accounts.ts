import type { AccountStatus, DataSource } from './enums';

export interface PermissionCheckResult {
  action: string;
  status: 'ALLOWED' | 'DENIED' | 'ERROR' | 'NOT_CHECKED';
  message?: string;
}

export interface AccountVerificationResult {
  verifiedAt: string;
  success: boolean;
  assumedRoleArn: string | null;
  callerAccountId: string | null;
  /** Regions that are enabled in the customer account (from ec2:DescribeRegions). */
  enabledRegions: string[];
  permissionChecks: PermissionCheckResult[];
  errorCode: string | null;
  errorMessage: string | null;
}

export interface CloudAccount {
  tenantId: string;
  /** 12-digit AWS account ID. Unique per tenant and used as the API identifier. */
  accountId: string;
  alias: string;
  roleArn: string;
  /** Generated by CloudSentry; never accepted from the client. */
  externalId: string;
  regions: string[];
  status: AccountStatus;
  dataSource: DataSource;
  /** Reserved for AWS Organizations support. */
  connectionType: 'ROLE' | 'ORGANIZATION_MEMBER';
  organizationId: string | null;
  lastVerification: AccountVerificationResult | null;
  lastScanId: string | null;
  lastScanAt: string | null;
  lastSuccessfulScanAt: string | null;
  createdBy: string;
  createdAt: string;
  updatedAt: string;
  version: number;
}

/** Instructions shown to the user to create the cross-account role. */
export interface AccountOnboardingInstructions {
  trustedPrincipalArn: string;
  externalId: string;
  roleName: string;
  roleArn: string;
  cloudFormationTemplate: string;
  cliCommand: string;
  trustPolicy: Record<string, unknown>;
  permissionsPolicy: Record<string, unknown>;
}
