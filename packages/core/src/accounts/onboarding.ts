import {
  CUSTOMER_ROLE_PERMISSION_STATEMENTS,
  CUSTOMER_ROLE_SESSION_SECONDS,
  type AccountOnboardingInstructions,
} from '@cloudsentry/shared-types';

export interface OnboardingInput {
  platformAccountId: string;
  customerAccountId: string;
  roleName: string;
  externalId: string;
}

export function trustPolicy(platformAccountId: string, externalId: string): Record<string, unknown> {
  return {
    Version: '2012-10-17',
    Statement: [
      {
        Sid: 'CloudSentryAssumeRole',
        Effect: 'Allow',
        Principal: { AWS: `arn:aws:iam::${platformAccountId}:root` },
        Action: 'sts:AssumeRole',
        // The external ID prevents the confused-deputy problem: CloudSentry only presents the ID it
        // generated for this tenant's registration of this account.
        Condition: { StringEquals: { 'sts:ExternalId': externalId } },
      },
    ],
  };
}

export function permissionsPolicy(): Record<string, unknown> {
  return {
    Version: '2012-10-17',
    Statement: CUSTOMER_ROLE_PERMISSION_STATEMENTS.map((s) => ({ ...s, Action: [...s.Action] })),
  };
}

/** Renders a CloudFormation YAML template that creates the read-only CloudSentry role. */
export function cloudFormationTemplate(input: OnboardingInput): string {
  const statements = CUSTOMER_ROLE_PERMISSION_STATEMENTS.map(
    (s) =>
      `              - Sid: ${s.Sid}\n                Effect: Allow\n                Action:\n${s.Action.map((a) => `                  - '${a}'`).join('\n')}\n                Resource: '*'`,
  ).join('\n');
  return `AWSTemplateFormatVersion: '2010-09-09'
Description: >-
  CloudSentry read-only cross-account role. Grants describe/list, CloudWatch metric and Cost Explorer
  read access only. CloudSentry cannot modify resources in this account.
Parameters:
  TrustedAccountId:
    Type: String
    Default: '${input.platformAccountId}'
    AllowedPattern: '^\\d{12}$'
    Description: AWS account ID of the CloudSentry platform.
  ExternalId:
    Type: String
    Default: '${input.externalId}'
    MinLength: 2
    Description: External ID generated by CloudSentry for this account connection.
Resources:
  CloudSentryRole:
    Type: AWS::IAM::Role
    Properties:
      RoleName: ${input.roleName}
      Description: Read-only access for CloudSentry cost optimization scans
      MaxSessionDuration: ${CUSTOMER_ROLE_SESSION_SECONDS}
      AssumeRolePolicyDocument:
        Version: '2012-10-17'
        Statement:
          - Effect: Allow
            Principal:
              AWS: !Sub 'arn:aws:iam::\${TrustedAccountId}:root'
            Action: 'sts:AssumeRole'
            Condition:
              StringEquals:
                'sts:ExternalId': !Ref ExternalId
      Policies:
        - PolicyName: CloudSentryReadOnly
          PolicyDocument:
            Version: '2012-10-17'
            Statement:
${statements}
      Tags:
        - Key: ManagedBy
          Value: CloudSentry
Outputs:
  RoleArn:
    Description: Paste this ARN into CloudSentry to verify the connection.
    Value: !GetAtt CloudSentryRole.Arn
`;
}

export function buildOnboardingInstructions(input: OnboardingInput): AccountOnboardingInstructions {
  return {
    trustedPrincipalArn: `arn:aws:iam::${input.platformAccountId}:root`,
    externalId: input.externalId,
    roleName: input.roleName,
    roleArn: `arn:aws:iam::${input.customerAccountId}:role/${input.roleName}`,
    cloudFormationTemplate: cloudFormationTemplate(input),
    cliCommand: [
      'aws cloudformation deploy',
      '--stack-name CloudSentryAccess',
      '--template-file cloudsentry-role.yaml',
      '--capabilities CAPABILITY_NAMED_IAM',
      `--parameter-overrides TrustedAccountId=${input.platformAccountId} ExternalId=${input.externalId}`,
    ].join(' \\\n  '),
    trustPolicy: trustPolicy(input.platformAccountId, input.externalId),
    permissionsPolicy: permissionsPolicy(),
  };
}
